//! Turns the alias list into a file each shell can source.
//!
//! The file for each shell:
//! 1. forgets whatever the previous version of this file defined, so removed aliases disappear
//! 2. defines the aliases (or functions, where an alias can't do the job)
//! 3. defines an `aka` wrapper that re-sources this file after every call, so changes show up
//!    in the current session (PowerShell uses a prompt hook instead, so native completion keeps
//!    working on `aka.exe`)
//! 4. registers tab completion for `aka` and passes completion through to the aliased commands

use std::fmt::Write as _;
use std::path::Path;

use anyhow::Result;
use clap_complete::env::EnvCompleter;

use crate::model::{Alias, Os, Shell, State};
use crate::paths::Paths;
use crate::{safety, store};

pub const COMPLETE_VAR: &str = "AKA_COMPLETE";
const VERSION: &str = env!("CARGO_PKG_VERSION");
const BOM: char = '\u{feff}';

pub struct RenderCtx<'a> {
    pub init_path: &'a Path,
    /// Absolute path of the aka binary, called by the completion scripts.
    pub completer: &'a str,
    pub os: Os,
}

pub fn render(shell: Shell, state: &State, rc: &RenderCtx) -> String {
    let entries: Vec<(&str, &Alias)> = state
        .aliases
        .aliases
        .iter()
        .filter(|(_, a)| a.applies_to(shell, rc.os))
        .map(|(n, a)| (n.as_str(), a))
        .collect();
    let mut out = format!(
        "# Generated by aka {VERSION}. Don't edit this file, it's rewritten on every change.\n\
         # Use `aka add`, `aka edit` or `aka rm` instead.\n\n"
    );
    match shell {
        Shell::Bash => bash(&mut out, &entries, rc),
        Shell::Zsh => zsh(&mut out, &entries, rc),
        Shell::Fish => fish(&mut out, &entries, rc),
        Shell::Powershell => powershell(&mut out, &entries, rc),
    }
    out
}

/// Rewrites all four init files and records which aka version wrote them.
pub fn write_init_files(paths: &Paths, state: &State) -> Result<()> {
    let completer = completer_path();
    for shell in Shell::ALL {
        let path = paths.init_file(shell);
        let rc = RenderCtx {
            init_path: &path,
            completer: &completer,
            os: Os::current(),
        };
        let mut text = render(shell, state, &rc);
        if shell == Shell::Powershell {
            // Windows PowerShell 5.1 reads BOM-less files as ANSI and mangles non-ASCII text.
            text.insert(0, BOM);
        }
        store::write_atomic(&path, &text)?;
    }
    store::write_atomic(&paths.version_file(), VERSION)
}

/// True when every init file matches what the current data would produce.
pub fn init_files_current(paths: &Paths, state: &State) -> bool {
    let completer = completer_path();
    Shell::ALL.iter().all(|&shell| {
        let path = paths.init_file(shell);
        let rc = RenderCtx {
            init_path: &path,
            completer: &completer,
            os: Os::current(),
        };
        std::fs::read_to_string(&path)
            .map(|text| text.trim_start_matches(BOM) == render(shell, state, &rc))
            .unwrap_or(false)
    })
}

/// Regenerates the init files when they're missing or were written by another
/// aka version (the completion scripts talk to the binary, so they must match).
pub fn ensure_fresh(paths: &Paths) -> Result<()> {
    let current = std::fs::read_to_string(paths.version_file()).unwrap_or_default();
    let missing = Shell::ALL.iter().any(|&s| !paths.init_file(s).exists());
    if current.trim() != VERSION || missing {
        store::regenerate(paths)?;
    }
    Ok(())
}

/// Prefers the `aka` found on PATH (a stable symlink for package managers)
/// over the resolved executable, which may live in a versioned directory.
pub fn completer_path() -> String {
    which::which("aka")
        .ok()
        .or_else(|| std::env::current_exe().ok())
        .map(|p| p.display().to_string())
        .unwrap_or_else(|| "aka".to_string())
}

fn registration(completer: &dyn EnvCompleter, rc: &RenderCtx) -> String {
    let mut buf = Vec::new();
    completer
        .write_registration(COMPLETE_VAR, "aka", "aka", rc.completer, &mut buf)
        .expect("writing to a Vec can't fail");
    String::from_utf8_lossy(&buf).trim().to_string()
}

/// A function body that calls `command`, passing the alias's arguments along.
fn body(name: &str, command: &str, args: &str, self_call: &str) -> String {
    format!("{} {args}", guard_self_calls(name, command, self_call))
}

/// Replaces every spot where the command calls the alias's own name (the first
/// word of each step in `a && b | c; d`) with `self_call`, so a function named
/// after a program runs the real program instead of calling itself forever.
/// Text inside quotes is left alone.
fn guard_self_calls(name: &str, command: &str, self_call: &str) -> String {
    let mut out = String::with_capacity(command.len() + self_call.len());
    let mut chars = command.char_indices().peekable();
    let mut at_command = true;
    while let Some(&(start, c)) = chars.peek() {
        if matches!(c, '|' | '&' | ';' | '(' | ')' | '{' | '}') {
            out.push(c);
            chars.next();
            at_command = true;
            continue;
        }
        if c.is_whitespace() {
            out.push(c);
            chars.next();
            continue;
        }
        // Read one word, keeping quoted parts whole.
        let mut quote = None;
        let mut end = command.len();
        while let Some(&(i, ch)) = chars.peek() {
            match quote {
                Some(q) if ch == q => quote = None,
                Some(_) => {}
                None if ch == '\'' || ch == '"' => quote = Some(ch),
                None if ch.is_whitespace() || "|&;(){}".contains(ch) => {
                    end = i;
                    break;
                }
                None => {}
            }
            chars.next();
        }
        let word = &command[start..end];
        if at_command && word == name {
            out.push_str(self_call);
            at_command = false;
        } else {
            out.push_str(word);
            // `VAR=value ls` and `time ls` still run `ls` as the command.
            let keeps_position = word == "time"
                || word.split_once('=').is_some_and(|(var, _)| {
                    !var.is_empty() && var.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
                });
            if !(at_command && keeps_position) {
                at_command = false;
            }
        }
    }
    out
}

fn confirm_question(command: &str) -> String {
    format!("aka: run `{command}`? [y/N] ")
}

// ---------------------------------------------------------------- bash

fn bash(out: &mut String, entries: &[(&str, &Alias)], rc: &RenderCtx) {
    let (funcs, aliases) = split(entries);
    let init = sh_quote(&rc.init_path.display().to_string());

    out.push_str(
        "for __aka_n in ${__AKA_ALIASES-}; do unalias \"$__aka_n\" 2>/dev/null; complete -r \"$__aka_n\" 2>/dev/null; done\n\
         for __aka_n in ${__AKA_FUNCS-}; do unset -f \"$__aka_n\" 2>/dev/null; complete -r \"$__aka_n\" 2>/dev/null; done\n\
         unset __aka_n\n",
    );
    let _ = writeln!(out, "__AKA_ALIASES={}", sh_quote(&names(&aliases)));
    let _ = writeln!(out, "__AKA_FUNCS={}\n", sh_quote(&names(&funcs)));

    for (name, alias) in &aliases {
        let _ = writeln!(out, "alias {name}={}", sh_quote(&alias.command));
    }
    for (name, alias) in &funcs {
        posix_confirm_function(out, name, alias);
    }

    let _ = write!(
        out,
        "\nfunction aka {{\n  command aka \"$@\"\n  local __aka_rc=$?\n  if [ -f {init} ]; then . {init}; fi\n  return $__aka_rc\n}}\n"
    );

    let _ = write!(
        out,
        "\nif [[ $- == *i* ]]; then\n{}\n",
        registration(&clap_complete::env::Bash, rc)
    );
    if !entries.is_empty() {
        out.push_str("\n__aka_expand() {\n  case \"$1\" in\n");
        for (name, alias) in entries {
            let _ = writeln!(
                out,
                "    {name}) __aka_reply={} ;;",
                sh_quote(&alias.command)
            );
        }
        out.push_str("  esac\n}\n");
        out.push_str(BASH_PASSTHROUGH);
        // `ls='ls -G'` style wrappers already get the right completion from bash.
        let passthrough: Vec<_> = entries
            .iter()
            .filter(|(n, a)| !safety::is_wrapper(n, &a.command))
            .copied()
            .collect();
        if !passthrough.is_empty() {
            let _ = writeln!(
                out,
                "complete -o bashdefault -o default -F __aka_complete_alias {}",
                names(&passthrough)
            );
        }
    }
    out.push_str("fi\n");
}

/// Completes `gco <TAB>` the way `git checkout <TAB>` would: rewrites the
/// completion words with the alias expanded and hands them to the real
/// command's completion function. Works with bash 3.2 (macOS) and bash-completion's lazy loading.
const BASH_PASSTHROUGH: &str = r#"__aka_complete_alias() {
  local __aka_reply=''
  __aka_expand "$1"
  [ -n "$__aka_reply" ] || return 0
  local -a __aka_words
  read -r -a __aka_words <<< "$__aka_reply"
  local __aka_cmd=${__aka_words[0]}
  local __aka_spec
  __aka_spec=$(complete -p "$__aka_cmd" 2>/dev/null)
  if [ -z "$__aka_spec" ]; then
    if declare -F _comp_complete_load >/dev/null 2>&1; then
      _comp_complete_load "$__aka_cmd" >/dev/null 2>&1
    elif declare -F _completion_loader >/dev/null 2>&1; then
      _completion_loader "$__aka_cmd" >/dev/null 2>&1
    fi
    __aka_spec=$(complete -p "$__aka_cmd" 2>/dev/null)
  fi
  local __aka_re='-F ([^ ]+)'
  [[ $__aka_spec =~ $__aka_re ]] || return 0
  local __aka_fn=${BASH_REMATCH[1]}
  [ "$__aka_fn" = __aka_complete_alias ] && [ "$__aka_cmd" = "$1" ] && return 0
  COMP_LINE="$__aka_reply${COMP_LINE#"$1"}"
  COMP_POINT=$((COMP_POINT + ${#__aka_reply} - ${#1}))
  COMP_WORDS=("${__aka_words[@]}" "${COMP_WORDS[@]:1}")
  COMP_CWORD=$((COMP_CWORD + ${#__aka_words[@]} - 1))
  "$__aka_fn" "$__aka_cmd" "${COMP_WORDS[COMP_CWORD]}" "${COMP_WORDS[COMP_CWORD-1]}"
}
"#;

// ---------------------------------------------------------------- zsh

fn zsh(out: &mut String, entries: &[(&str, &Alias)], rc: &RenderCtx) {
    let (funcs, aliases) = split(entries);
    let init = sh_quote(&rc.init_path.display().to_string());

    out.push_str(
        "for __aka_n in ${=__AKA_ALIASES-}; do unalias \"$__aka_n\" 2>/dev/null; done\n\
         for __aka_n in ${=__AKA_FUNCS-}; do unfunction \"$__aka_n\" 2>/dev/null; done\n\
         unset __aka_n\n",
    );
    let _ = writeln!(out, "__AKA_ALIASES={}", sh_quote(&names(&aliases)));
    let _ = writeln!(out, "__AKA_FUNCS={}\n", sh_quote(&names(&funcs)));

    for (name, alias) in &aliases {
        let _ = writeln!(out, "alias {name}={}", sh_quote(&alias.command));
    }
    for (name, alias) in &funcs {
        posix_confirm_function(out, name, alias);
    }

    let _ = write!(
        out,
        "\nfunction aka {{\n  command aka \"$@\"\n  local __aka_rc=$?\n  if [[ -f {init} ]]; then source {init}; fi\n  return $__aka_rc\n}}\n"
    );

    // zsh expands plain aliases before completing, so they get the real
    // command's completion for free. Functions need an explicit compdef.
    let _ = write!(
        out,
        "\nif [[ -o interactive ]] && (( $+functions[compdef] )); then\n{}\n",
        registration(&clap_complete::env::Zsh, rc)
    );
    for (name, alias) in &funcs {
        if let Some(cmd) = safety::first_words(&alias.command).first() {
            let _ = writeln!(out, "compdef {name}={cmd}");
        }
    }
    // Show each alias with its description when completing a command name.
    // zsh lists plain aliases without any, so aka adds its own group ahead of
    // the usual command completion (kept in __aka_command_prev).
    let descs: Vec<String> = entries
        .iter()
        .map(|(name, alias)| {
            let about = alias.description.as_deref().unwrap_or(&alias.command);
            sh_quote(&format!("{name}:{about}"))
        })
        .collect();
    let _ = write!(out, "__aka_descs=({})\n{ZSH_DESCRIBE}", descs.join(" "));
    out.push_str("fi\n");
}

const ZSH_DESCRIBE: &str = r#"if [[ ${_comps[-command-]} != _aka_command ]]; then
  __aka_command_prev=${_comps[-command-]:-_command_names}
fi
_aka_command() {
  (( ${#__aka_descs} )) && _describe -t aka-aliases 'aka alias' __aka_descs
  "$__aka_command_prev" "$@"
}
compdef _aka_command -command-
# aka's aliases already appear above with descriptions; don't list them twice.
zstyle ':completion:*:-command-:*:aliases' ignored-patterns ${=__AKA_ALIASES}
"#;

fn posix_confirm_function(out: &mut String, name: &str, alias: &Alias) {
    let _ = write!(
        out,
        "unalias {name} 2>/dev/null\n\
         function {name} {{\n  \
           printf '%s' {question} >&2\n  \
           local __aka_r\n  \
           read -r __aka_r\n  \
           case \"$__aka_r\" in [yY]|[yY][eE][sS]) ;; *) return 1 ;; esac\n  \
           {body}\n\
         }}\n",
        question = sh_quote(&confirm_question(&alias.command)),
        body = body(name, &alias.command, "\"$@\"", &format!("command {name}")),
    );
}

// ---------------------------------------------------------------- fish

fn fish(out: &mut String, entries: &[(&str, &Alias)], rc: &RenderCtx) {
    let init = fish_quote(&rc.init_path.display().to_string());

    out.push_str(
        "for __aka_n in $__AKA_FUNCS\n    functions --erase -- $__aka_n\nend\nset --erase __aka_n\n",
    );
    out.push_str("set --global __AKA_FUNCS");
    for (name, _) in entries {
        let _ = write!(out, " {}", fish_quote(name));
    }
    out.push_str("\n\n");

    for (name, alias) in entries {
        let description = alias
            .description
            .clone()
            .unwrap_or_else(|| alias.command.clone());
        let _ = write!(out, "function {name}");
        // `--wraps` gives the function the wrapped command's completions. Skip it for
        // `ls='ls -G'` style aliases, where fish would complete the function with itself.
        if !safety::is_wrapper(name, &alias.command) {
            let _ = write!(out, " --wraps {}", fish_quote(&alias.command));
        }
        let _ = writeln!(out, " --description {}", fish_quote(&description));
        if alias.confirm {
            let _ = write!(
                out,
                "    read --prompt-str {} --local __aka_r\n    or return 1\n    \
                 if not string match --quiet --ignore-case --regex '^(y|yes)$' -- $__aka_r\n        return 1\n    end\n",
                fish_quote(&confirm_question(&alias.command))
            );
        }
        let _ = writeln!(
            out,
            "    {}\nend",
            body(name, &alias.command, "$argv", &format!("command {name}"))
        );
    }

    let _ = write!(
        out,
        "\nfunction aka --description 'Manage your shell aliases'\n    command aka $argv\n    set --local __aka_rc $status\n    \
         if test -f {init}\n        source {init}\n    end\n    return $__aka_rc\nend\n"
    );
    let _ = write!(
        out,
        "\nif status is-interactive\n    complete --erase --command aka\n    {}\nend\n",
        registration(&clap_complete::env::Fish, rc)
    );
}

// ---------------------------------------------------------------- PowerShell

fn powershell(out: &mut String, entries: &[(&str, &Alias)], rc: &RenderCtx) {
    let init = ps_quote(&rc.init_path.display().to_string());

    out.push_str(
        "foreach ($__aka_n in @($global:__AKA_FUNCS)) {\n    \
           if ($__aka_n) {\n        \
             Remove-Item -LiteralPath \"Function:\\$__aka_n\" -Force -ErrorAction SilentlyContinue\n        \
             Remove-Item -LiteralPath \"Alias:\\$__aka_n\" -Force -ErrorAction SilentlyContinue\n    \
           }\n\
         }\n\
         Remove-Variable -Name __aka_n -ErrorAction SilentlyContinue\n",
    );
    let quoted: Vec<String> = entries.iter().map(|(n, _)| ps_quote(n)).collect();
    let _ = writeln!(out, "$global:__AKA_FUNCS = @({})\n", quoted.join(", "));

    // A one-word command becomes a real PowerShell alias, which completes like
    // the command it points to. Set-Alias can't carry arguments, so anything
    // longer becomes a function, with a completer below that passes Tab through.
    // Built-in aliases with the same name (gp, gc, ls...) would win over
    // functions, so they're dropped for the session.
    let mut expansions = Vec::new();
    for (name, alias) in entries {
        let _ = writeln!(
            out,
            "Remove-Item -LiteralPath {} -Force -ErrorAction SilentlyContinue",
            ps_quote(&format!("Alias:\\{name}"))
        );
        let command = alias.command.trim();
        if !alias.confirm && !command.contains(char::is_whitespace) && command != *name {
            let _ = writeln!(
                out,
                "Set-Alias -Name {} -Value {} -Scope Global -Force",
                ps_quote(name),
                ps_quote(command)
            );
            continue;
        }
        // `ls = ls -G` style wrappers already complete as themselves; passing
        // them through would call this same completer again, forever.
        if !safety::is_wrapper(name, command) {
            expansions.push(format!("{} = {}", ps_quote(name), ps_quote(command)));
        }
        let call = body(
            name,
            &alias.command,
            "@args",
            &format!(
                "& (Get-Command -Name {} -CommandType Application,Cmdlet | Select-Object -First 1)",
                ps_quote(name)
            ),
        );
        if alias.confirm {
            let _ = write!(
                out,
                "function global:{name} {{\n    \
                   $__aka_r = Read-Host {}\n    \
                   if ($__aka_r -notmatch '^(y|yes)$') {{ return }}\n    \
                   {call}\n\
                 }}\n",
                // Read-Host adds its own ": " after the question
                ps_quote(&format!("aka: run `{}`? [y/N]", alias.command))
            );
        } else {
            let _ = writeln!(out, "function global:{name} {{ {call} }}");
        }
    }

    if !expansions.is_empty() {
        let _ = write!(
            out,
            "\n$global:__AkaExpand = @{{ {} }}\n{PS_PASSTHROUGH}",
            expansions.join("; ")
        );
    }

    let _ = write!(
        out,
        "\n$global:__AkaInit = {init}\n\
         $global:__AkaStamp = (Get-Item -LiteralPath $global:__AkaInit -ErrorAction SilentlyContinue).LastWriteTimeUtc\n\
         # Reload this file before each prompt if aka changed it.\n\
         if (-not $global:__AkaPromptHooked) {{\n    \
           $global:__AkaPromptHooked = $true\n    \
           $global:__AkaPrompt = $function:prompt\n    \
           function global:prompt {{\n        \
             $t = (Get-Item -LiteralPath $global:__AkaInit -ErrorAction SilentlyContinue).LastWriteTimeUtc\n        \
             if ($t -and $t -ne $global:__AkaStamp) {{ . $global:__AkaInit }}\n        \
             & $global:__AkaPrompt\n    \
           }}\n\
         }}\n\n{}\n",
        registration(&clap_complete::env::Powershell, rc)
    );
}

/// Completes `gco ma<Tab>` like `git checkout ma<Tab>`: rewrites the line with
/// the alias expanded and hands it to PowerShell's own completion engine.
const PS_PASSTHROUGH: &str = r#"$global:__AkaComplete = {
    param($wordToComplete, $commandAst, $cursorPosition)
    $name = $commandAst.GetCommandName()
    $expansion = $global:__AkaExpand[$name]
    if (-not $expansion) { return }
    $text = $commandAst.Extent.Text
    $line = $expansion + $text.Substring($name.Length)
    $column = $cursorPosition - $commandAst.Extent.StartOffset + $expansion.Length - $name.Length
    (TabExpansion2 -inputScript $line -cursorColumn $column).CompletionMatches
}
foreach ($__aka_n in $global:__AkaExpand.Keys) {
    Register-ArgumentCompleter -Native -CommandName $__aka_n -ScriptBlock $global:__AkaComplete
}
Remove-Variable -Name __aka_n -ErrorAction SilentlyContinue
"#;

// ---------------------------------------------------------------- helpers

/// Aliases that must be functions (they ask before running) versus plain aliases.
#[allow(clippy::type_complexity)]
fn split<'a>(
    entries: &[(&'a str, &'a Alias)],
) -> (Vec<(&'a str, &'a Alias)>, Vec<(&'a str, &'a Alias)>) {
    entries.iter().partition(|(_, a)| a.confirm)
}

fn names(entries: &[(&str, &Alias)]) -> String {
    entries
        .iter()
        .map(|(n, _)| *n)
        .collect::<Vec<_>>()
        .join(" ")
}

pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

pub fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', r"\\").replace('\'', r"\'"))
}

pub fn ps_quote(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        // PowerShell also treats curly single quotes as quote characters.
        if matches!(c, '\'' | '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{201B}') {
            out.push(c);
        }
        out.push(c);
    }
    out.push('\'');
    out
}

